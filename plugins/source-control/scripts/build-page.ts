/// <reference types="bun-types" />
/**
 * Bundle the review page (`src/app/page/index.tsx`) into one ES module and
 * write it as a string export. The server serves it at `/page.js`, and the
 * app's shims import it on first open, since plugin app bundles have no code
 * splitting. Modules bb's plugin runtime provides are read from
 * `globalThis.__bbPluginRuntime`, as `bb plugin build` shims them, so the
 * page shares the host's React and SDK.
 *
 * `PAGE_SOURCE_HASH` covers every plugin source file the bundle took in;
 * `page-bundle.test.ts` fails when the committed bundle is older than them.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as PluginSdkApp from "@get-bb/plugin-sdk/app";
import * as PierreDiffs from "@pierre/diffs";
import * as PierreDiffsReact from "@pierre/diffs/react";
import type { BunPlugin } from "bun";
import * as React from "react";
import * as JsxRuntime from "react/jsx-runtime";

const root = fileURLToPath(new URL("..", import.meta.url));
const here = (path: string) => fileURLToPath(new URL(path, new URL("..", import.meta.url)));
const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");

/** Specifier → the `__bbPluginRuntime` slot that holds it, and the package, for its export names. */
const RUNTIME: Record<string, { slot: string; exports: object }> = {
  react: { slot: "react", exports: React },
  "react/jsx-runtime": { slot: "jsxRuntime", exports: JsxRuntime },
  "@get-bb/plugin-sdk/app": { slot: "pluginSdkApp", exports: PluginSdkApp },
  "@pierre/diffs": { slot: "pierreDiffs", exports: PierreDiffs },
  "@pierre/diffs/react": { slot: "pierreDiffsReact", exports: PierreDiffsReact },
};

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** The runtime slot as a module: its default and every named export the package has. */
function shim(specifier: string): string {
  const { slot, exports } = RUNTIME[specifier]!;
  const names = Object.keys(exports).filter((name) => name !== "default" && IDENTIFIER.test(name));
  return [
    `const runtime = globalThis.__bbPluginRuntime;`,
    `if (runtime == null || runtime.${slot} == null) throw new Error(${JSON.stringify(
      `Cannot load "${specifier}": the review page must be loaded by the BB app.`,
    )});`,
    `const slot = runtime.${slot};`,
    `const value = "default" in slot ? slot.default : slot;`,
    `export default value;`,
    `export const { ${names.join(", ")} } = value;`,
  ].join("\n");
}

/** Plugin files the bundle read, relative to the plugin root. */
const sources = new Set<string>();

const runtimePlugin: BunPlugin = {
  name: "bb-plugin-runtime",
  setup(build) {
    build.onResolve(
      { filter: /^(react(\/jsx-runtime)?|@get-bb\/plugin-sdk\/app|@pierre\/diffs(\/react)?)$/ },
      (args) => ({
        path: args.path,
        namespace: "bb-runtime",
      }),
    );
    build.onResolve({ filter: /^react-dom(\/.*)?$|^react\/jsx-dev-runtime$/ }, (args) => {
      throw new Error(
        `${args.path} is not in bb's plugin runtime; the page must not import it (from ${args.importer}).`,
      );
    });
    build.onLoad({ filter: /.*/, namespace: "bb-runtime" }, async (args) => ({
      contents: shim(args.path),
      loader: "js",
    }));
    build.onLoad({ filter: /\.tsx?$/ }, async (args) => {
      const path = relative(root, args.path);
      if (!path.startsWith("..") && !path.includes("node_modules")) sources.add(path);
      return {
        contents: await readFile(args.path, "utf8"),
        loader: args.path.endsWith("x") ? "tsx" : "ts",
      };
    });
  },
};

const result = await Bun.build({
  entrypoints: [here("src/app/page/index.tsx")],
  format: "esm",
  target: "browser",
  minify: true,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  plugins: [runtimePlugin],
});
if (!result.success) throw new AggregateError(result.logs, "review page bundle failed");
const source = await result.outputs[0]!.text();

async function pageSourceHash(paths: readonly string[]): Promise<string> {
  const hash = createHash("sha256");
  for (const path of [...paths].sort())
    hash.update(`${path}\0${await readFile(here(path), "utf8")}\0`);
  return hash.digest("hex");
}

const files = [...sources].sort();
const etag = `"${sha256(source).slice(0, 32)}"`;
await writeFile(
  here("generated/page-bundle.ts"),
  `// Generated by \`bun run build:page\` from src/app/page/index.tsx. Do not edit.\n` +
    `export const PAGE_ETAG = ${JSON.stringify(etag)};\n` +
    `export const PAGE_SOURCE_HASH = ${JSON.stringify(await pageSourceHash(files))};\n` +
    `/** The plugin files hashed into PAGE_SOURCE_HASH. */\n` +
    `export const PAGE_SOURCES = ${JSON.stringify(files, null, 2)};\n` +
    `export default ${JSON.stringify(source)};\n`,
);
// The app's shim reads only this, so the eager bundle never carries the page source.
await writeFile(
  here("generated/page-version.ts"),
  `// Generated by \`bun run build:page\`. Do not edit.\nexport const PAGE_ETAG = ${JSON.stringify(etag.slice(1, -1))};\n`,
);
console.log(
  `Wrote generated/page-bundle.ts (${source.length} bytes, ${files.length} source files)`,
);
