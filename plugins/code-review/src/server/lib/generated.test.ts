import { expect, test } from "bun:test";
import { isGenerated, parseGitattributes } from "./generated.ts";

const none = parseGitattributes("");

test("well-known lockfiles, bundles, and generator outputs are generated", () => {
  const paths = [
    "bun.lock",
    "web/package-lock.json",
    "pnpm-lock.yaml",
    "Cargo.lock",
    "go.sum",
    "dist/app.min.js",
    "dist/app.js.map",
    "api/v1/user.pb.go",
    "proto/user_pb2.py",
    "src/__generated__/query.graphql.ts",
    "lib/model.g.dart",
    "gradlew",
  ];
  expect(paths.filter((path) => isGenerated(path, null, none))).toEqual(paths);
});

test("ordinary source is not generated", () => {
  const paths = [
    "src/lock.ts",
    "go.mod",
    "package.json",
    "composer.json",
    "Pipfile",
    "src/generator.ts",
    "README.md",
  ];
  expect(paths.filter((path) => isGenerated(path, null, none))).toEqual([]);
});

test("a generator's header at the top of a new file marks it generated", () => {
  const header =
    "@@ -0,0 +1,3 @@\n+// Code generated by protoc-gen-go. DO NOT EDIT.\n+package api\n+";
  const lower = "@@ -40,3 +40,4 @@\n a\n+// Code generated by hand. DO NOT EDIT.\n b";
  expect(isGenerated("api/user.go", header, none)).toBe(true);
  // Lower in the file, the same words are a comment about something else.
  expect(isGenerated("api/user.go", lower, none)).toBe(false);
});

test("a generator's own source, which writes the stamp as a string, is not generated", () => {
  const source =
    '@@ -0,0 +1,2 @@\n+const header = "// Code generated by tool. DO NOT EDIT.";\n+export {};';
  expect(isGenerated("tools/gen.ts", source, none)).toBe(false);
});

test("removed lines do not use up the lines the stamp is looked for in", () => {
  const license = ["-// one", "-// two", "-// three", "-// four", "-// five"];
  const patch = ["@@ -1,5 +1,1 @@", ...license, "+// @generated by relay"].join("\n");
  expect(isGenerated("src/schema.ts", patch, none)).toBe(true);
});

test("linguist-generated in .gitattributes marks files, by name anywhere or by a rooted path", () => {
  const rules = parseGitattributes(
    [
      "# Generated by tools/ephemeralgen.",
      "* text=auto",
      "k8s/ephemeral/*.yaml linguist-generated=true",
      "*.snap linguist-generated",
      "packages/**/generated/* linguist-generated\r",
      "/vendor/** linguist-generated",
    ].join("\n"),
  );
  expect(isGenerated("k8s/ephemeral/dev.yaml", null, rules)).toBe(true);
  expect(isGenerated("k8s/ephemeral/nested/dev.yaml", null, rules)).toBe(false);
  expect(isGenerated("other/k8s/ephemeral/dev.yaml", null, rules)).toBe(false);
  expect(isGenerated("src/__snapshots__/app.test.ts.snap", null, rules)).toBe(true);
  expect(isGenerated("packages/generated/a.ts", null, rules)).toBe(true);
  expect(isGenerated("packages/x/y/generated/a.ts", null, rules)).toBe(true);
  expect(isGenerated("packages/x/generated/deep/a.ts", null, rules)).toBe(false);
  expect(isGenerated("vendor/lib/a.go", null, rules)).toBe(true);
});

test("a pattern naming a directory does not reach the files in it, as in git", () => {
  const rules = parseGitattributes("/schema/ linguist-generated\nschema linguist-generated");
  expect(isGenerated("schema/types/user.ts", null, rules)).toBe(false);
});

test("quoted patterns and character classes match, so their exclusions hold", () => {
  const rules = parseGitattributes(
    [
      '"docs/my schema.generated.ts" -linguist-generated',
      "src/[a-z].generated.ts -linguist-generated",
      "src/[!a-z]*.ts linguist-generated",
    ].join("\n"),
  );
  expect(isGenerated("docs/my schema.generated.ts", null, rules)).toBe(false);
  expect(isGenerated("src/q.generated.ts", null, rules)).toBe(false);
  expect(isGenerated("src/Q.generated.ts", null, rules)).toBe(true);
  expect(isGenerated("src/9.ts", null, rules)).toBe(true);
});

test("a pathological pattern is matched quickly", () => {
  const rules = parseGitattributes(`${"*a".repeat(18)}b.ts linguist-generated`);
  const started = performance.now();
  expect(isGenerated(`${"a".repeat(36)}c.ts`, null, rules)).toBe(false);
  expect(performance.now() - started).toBeLessThan(200);
});

test("the repository can unmark a file the list would fold, and the last matching line wins", () => {
  const rules = parseGitattributes(
    [
      "*.lock linguist-generated=false",
      "gen/** linguist-generated",
      "gen/keep.ts -linguist-generated",
      "go.sum !linguist-generated",
    ].join("\n"),
  );
  expect(isGenerated("yarn.lock", null, rules)).toBe(false);
  expect(isGenerated("gen/deep/out.ts", null, rules)).toBe(true);
  expect(isGenerated("gen/keep.ts", null, rules)).toBe(false);
  // `!` hands the file back to the list.
  expect(isGenerated("go.sum", null, rules)).toBe(true);
});
