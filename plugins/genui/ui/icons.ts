/**
 * The BB icon a spec's icon name means, or null when BB has no such icon
 * (callers then draw nothing rather than BB's Zap fallback). Accepts any
 * case and separator, lucide/heroicons spellings, and a trailing "Icon".
 */
export function resolveIconName(name: string): string | null {
  const key = name.replace(/[-_\s.]+/g, "").toLowerCase();
  if (key === "") return null;
  const found = BY_KEY.get(key) ?? (Object.hasOwn(ALIASES, key) ? ALIASES[key] : undefined);
  if (found !== undefined) return found;
  // `TrashIcon`, `trash-icon`: the component name some icon libraries export.
  return key.endsWith("icon") && key.length > 4 ? resolveIconName(key.slice(0, -4)) : null;
}
