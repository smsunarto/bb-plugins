/** Resolve a repository root without invoking a shell. */
function findGitRoot(start: string): string | null {
  let candidate = resolveRealPath(start);
  if (isFile(candidate)) candidate = path.dirname(candidate);
  const result = spawnSync("git", ["-C", candidate, "rev-parse", "--show-toplevel"]);
  if (result.status !== 0 || !result.stdout) return null;
  let root: string;
  try {
    root = resolveRealPath(new TextDecoder("utf-8", { fatal: true }).decode(result.stdout).trim());
  } catch {
    return null;
  }
  return isDirectory(root) ? root : null;
}

/** Read a small UTF-8 Git blob addressed by a validated patch object ID. */
function readGitBlob(
  repoRoot: string,
  objectId: string,
  cache: Map<string, string | null>,
): string | null {
  const normalizedId = objectId.toLowerCase();
  const cached = cache.get(normalizedId);
  if (cached !== undefined || cache.has(normalizedId)) return cached ?? null;
  if (!normalizedId || /^0+$/.test(normalizedId)) {
    cache.set(normalizedId, null);
    return null;
  }

  const objectType = spawnSync("git", ["-C", repoRoot, "cat-file", "-t", normalizedId]);
  if (
    objectType.status !== 0 ||
    !objectType.stdout ||
    objectType.stdout.toString().trim() !== "blob"
  ) {
    cache.set(normalizedId, null);
    return null;
  }

  const sizeResult = spawnSync("git", ["-C", repoRoot, "cat-file", "-s", normalizedId]);
  const sizeText = sizeResult.stdout ? sizeResult.stdout.toString().trim() : "";
  if (!/^[+-]?[0-9]+$/.test(sizeText)) {
    cache.set(normalizedId, null);
    return null;
  }
  const size = Number(sizeText);
  if (sizeResult.status !== 0 || size > MAX_EXPANDABLE_BLOB_BYTES) {
    cache.set(normalizedId, null);
    return null;
  }

  const payloadResult = spawnSync("git", ["-C", repoRoot, "cat-file", "-p", normalizedId], {
    maxBuffer: MAX_EXPANDABLE_BLOB_BYTES + 1024,
  });
  const payload = payloadResult.stdout;
  if (
    payloadResult.status !== 0 ||
    !payload ||
    payload.length > MAX_EXPANDABLE_BLOB_BYTES ||
    payload.includes(0)
  ) {
    cache.set(normalizedId, null);
    return null;
  }
  let contents: string;
  try {
    contents = new TextDecoder("utf-8", { fatal: true }).decode(payload);
  } catch {
    cache.set(normalizedId, null);
    return null;
  }
  cache.set(normalizedId, contents);
  return contents;
}

