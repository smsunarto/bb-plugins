/** Resolve like Python's Path.resolve(): absolute, with symlinks followed. */
function resolveRealPath(target: string): string {
  const absolute = path.resolve(target);
  try {
    return fs.realpathSync(absolute);
  } catch {
    const parent = path.dirname(absolute);
    if (parent === absolute) return absolute;
    return path.join(resolveRealPath(parent), path.basename(absolute));
  }
}

function isFile(target: string): boolean {
  try {
    return fs.statSync(target).isFile();
  } catch {
    return false;
  }
}

function isDirectory(target: string): boolean {
  try {
    return fs.statSync(target).isDirectory();
  } catch {
    return false;
  }
}

function readTextFile(target: string): string {
  return new TextDecoder("utf-8", { fatal: true }).decode(fs.readFileSync(target));
}

/** Collect every *.mdx file below `root`, as paths relative to `root`. */
function collectMdxFiles(root: string): string[] {
  const found: string[] = [];
  const walk = (relative: string): void => {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(path.join(root, relative), { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const next = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walk(next);
      else if (entry.isFile() && entry.name.toLowerCase().endsWith(".mdx")) found.push(next);
    }
  };
  walk("");
  return found;
}

/** Order paths by their components, matching how Python sorted Path objects. */
function comparePaths(left: string, right: string): number {
  const leftParts = left.split("/");
  const rightParts = right.split("/");
  const limit = Math.min(leftParts.length, rightParts.length);
  for (let index = 0; index < limit; index += 1) {
    const result = compareStrings(leftParts[index], rightParts[index]);
    if (result !== 0) return result;
  }
  return leftParts.length - rightParts.length;
}

