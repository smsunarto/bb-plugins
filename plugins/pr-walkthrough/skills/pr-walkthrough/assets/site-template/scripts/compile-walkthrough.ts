const USAGE = `usage: compile-walkthrough.ts [-h] [--input INPUT] [--output OUTPUT] [--diff DIFF]
                              [--include-full-context] [--repo REPO]

Compile a canonical multi-file MDX walkthrough into review UI data.
`;

function usageError(message: string): never {
  process.stderr.write(USAGE);
  process.stderr.write(`compile-walkthrough.ts: error: ${message}\n`);
  process.exit(2);
}

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function parseCliArgs(
  argv: string[],
  optionNames: string[],
  flagNames: string[],
): { values: Map<string, string>; flags: Set<string> } {
  const values = new Map<string, string>();
  const flags = new Set<string>();
  let index = 0;
  while (index < argv.length) {
    const token = argv[index];
    if (token === "-h" || token === "--help") {
      process.stdout.write(USAGE);
      process.exit(0);
    }
    const equals = token.indexOf("=");
    const name = equals >= 0 ? token.slice(0, equals) : token;
    if (equals < 0 && flagNames.includes(name)) {
      flags.add(name);
      index += 1;
      continue;
    }
    if (optionNames.includes(name)) {
      if (equals >= 0) {
        values.set(name, token.slice(equals + 1));
        index += 1;
        continue;
      }
      const value: string | undefined = argv[index + 1];
      if (value === undefined) usageError(`argument ${name}: expected one argument`);
      values.set(name, value);
      index += 2;
      continue;
    }
    usageError(`unrecognized arguments: ${token}`);
  }
  return { values, flags };
}

/** Escape non-ASCII the way Python's json.dumps did, so output stays byte-stable. */
function ensureAscii(value: string): string {
  return value.replace(
    /[\u0080-\uffff]/g,
    (character) => `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );
}

function isSystemError(error: unknown): boolean {
  return error instanceof Error && typeof (error as NodeJS.ErrnoException).code === "string";
}

function main(argv: string[]): number {
  const parsed = parseCliArgs(
    argv,
    ["--input", "--output", "--diff", "--repo"],
    ["--include-full-context"],
  );
  const inputPath = parsed.values.get("--input") ?? "src/content/walkthrough";
  const outputPath = parsed.values.get("--output") ?? "src/data/walkthrough.generated.json";
  const diffPath = parsed.values.get("--diff") ?? "src/data/walkthrough.patch";
  const repoArg = parsed.values.get("--repo");

  let data: WalkthroughData;
  try {
    const patch = isFile(diffPath) ? readTextFile(diffPath) : "";
    const siteRoot = path.dirname(path.dirname(resolveRealPath(fileURLToPath(import.meta.url))));
    const markerPath = path.join(siteRoot, "src", "data", FULL_CONTEXT_MARKER_NAME);
    const includeFullContext = parsed.flags.has("--include-full-context") || isFile(markerPath);
    let repoRoot: string | null = null;
    if (includeFullContext) {
      repoRoot = findGitRoot(repoArg ?? process.cwd());
      if (repoRoot === null) {
        throw new CompileError(
          "full context was requested, but no Git repository could be resolved",
        );
      }
    }
    data = isDirectory(inputPath)
      ? compileWalkthroughDir(inputPath, patch, repoRoot)
      : compileMdx(readTextFile(inputPath), patch, repoRoot);
  } catch (error) {
    if (error instanceof CompileError || isSystemError(error)) {
      fail(`walkthrough compile failed: ${(error as Error).message}`);
    }
    throw error;
  }

  fs.mkdirSync(path.dirname(path.resolve(outputPath)), { recursive: true });
  fs.writeFileSync(outputPath, `${ensureAscii(JSON.stringify(data, null, 2))}\n`, "utf8");
  process.stdout.write(`${outputPath}\n`);
  return 0;
}

const invokedAs = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedAs === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
