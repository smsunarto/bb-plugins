import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

/** Content-address the selectors so independently released plugins cannot restyle each other. */
export function sharedStyles(source: string) {
  const canonical = source.replace(/bbui-[a-f0-9]{12}-/g, "bbui-");
  const names = [...new Set(canonical.match(/bbui-[a-z][a-z-]*/g))].sort();
  const fingerprint = createHash("sha256")
    .update(canonical + names.join("\n"))
    .digest("hex")
    .slice(0, 12);
  const prefix = `bbui-${fingerprint}-`;
  const css = canonical.replace(/bbui-/g, prefix);
  const entries = names.map((name) => {
    const key = name.slice(5);
    return `  ${/^[a-z]+$/.test(key) ? key : JSON.stringify(key)}: "${name.replace("bbui-", prefix)}",`;
  });
  const classes = `// Generated by scripts/shared-ui-styles.ts; do not edit.\nexport const styles = {\n${entries.join("\n")}\n} as const;\n`;
  return { css, classes };
}

if (import.meta.main) {
  const path = "packages/ui/src/controls.css";
  const result = sharedStyles(readFileSync(path, "utf8"));
  if (process.argv.includes("--check")) {
    if (
      readFileSync(path, "utf8") !== result.css ||
      readFileSync("packages/ui/src/styles.ts", "utf8") !== result.classes
    )
      throw new Error("Run bun scripts/shared-ui-styles.ts after changing shared control styles");
  } else {
    writeFileSync(path, result.css);
    writeFileSync("packages/ui/src/styles.ts", result.classes);
  }
}
